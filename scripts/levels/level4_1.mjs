// Уровень 4 «Заморозка-2007» — Гигантский холодильник оригинала (docs/refs/level_4_*.png).
// Босса нет, как в оригинале. Таймер 3:00 (свойство карты), пол скользкий, тающие платформы —
// вещи 2007 года во льду, сосульки под трубами, телефоны-раскладушки скользят по полу.
// Маршрут (по кадрам: начало → пол с банками и полками → подъём по трубам → верхний ярус с
// морозильными блоками → уступ над шахтой → трубы вверх к проёму вентиляции):
//   A. вправо по полу, 4 экрана (строки 30–44, пол — строка 43);
//   B. вверх по трубам, 2 экрана (колонки 48–63);
//   C. вправо по верхнему ярусу, 4 экрана (строки 15–29, пол — строка 24, y = 144 на экране);
//   D. вверх по трубам к выходу, 2 экрана (колонки 96–111).
// Мебель, трубы, фермы — oneway; сплошной только пол. Всё, на что прыгать, — не выше 32 px.
import { placers } from './common.mjs';
import * as F from './fridge-art.mjs';
import { MapBuilder, TILE } from './lib.mjs';

export function buildLevel4Fridge() {
  const m = new MapBuilder(112, 45);
  const { box, pair, enemy, tc } = placers(m);
  const y = (row) => row * TILE;
  const FA = 43; // пол низа
  const FC = 24; // пол верхнего яруса
  m.properties.timer = 180;
  m.properties.slippery = true;

  const pipe = (col, w, top, valveAt = -1) => m.prop(F.pipe(w, valveAt), col, top + 1);
  const girder = (col, w, top) => m.prop(F.girder(w), col, top + 1);
  const icicle = (col, pipeTop) =>
    m.pointPx('enemy', col * TILE + 8, y(pipeTop + 1) + 16, { kind: 'icicle' });
  const melt = (col, top, item) => m.pointPx('melt', col * TILE + TILE, y(top), { kind: item });

  // ——— Фон: стенка, стойки, полосы инея, решётки ———
  m.paint((p) => {
    F.wall(p, 0, 0, m.cols * TILE, m.rows * TILE);
    for (let x = 40; x < m.cols * TILE; x += 112) F.pole(p, x, 0, m.rows * TILE);
    for (const [col, row, len] of [
      [5, 30, 40],
      [6, 30, 64],
      [13, 30, 52],
      [25, 30, 70],
      [38, 30, 44],
      [44, 30, 60],
      [51, 15, 50],
      [61, 28, 40],
      [70, 15, 60],
      [78, 15, 36],
      [86, 15, 70],
      [93, 15, 44],
      [99, 0, 50],
      [108, 13, 60],
      [101, 25, 70],
    ])
      F.frostStrand(p, col * TILE, y(row), len);
    for (const [col, row, w, h] of [
      [2, 31, 3, 2],
      [2, 35, 3, 2],
      [9, 35, 3, 2],
      [20, 31, 3, 2],
      [34, 31, 3, 2],
      [66, 15, 3, 2],
      [82, 15, 3, 2],
      [106, 2, 3, 2],
      [98, 16, 3, 2],
    ])
      F.vent(p, col * TILE, y(row), w * TILE, h * TILE);
    // Пол низа и верхнего яруса (в яме — пусто: шахта).
    F.crateFloor(p, 0, y(FA), 64 * TILE, 2 * TILE);
    F.crateFloor(p, 64 * TILE, y(FC), 20 * TILE, 6 * TILE);
    F.crateFloor(p, 89 * TILE, y(FC), 7 * TILE, 6 * TILE);
  });
  m.solid(0, 63, FA, FA + 1);
  m.solid(64, 83, FC, FC + 5);
  m.solid(89, 95, FC, FC + 5);
  const snow = (col, row, w = 16) => m.decor((p) => F.snowPile(p, col * TILE, y(row), w));

  // ——— A. Пол, экран 0 (0–15): старт на банках, ящики, полка ———
  m.prop(F.cans(8), 0, FA); // 0–7, верх 41
  m.point('spawn', 3, 41);
  m.point('respawn', 3, 41);
  box(8, FA);
  box(9, FA, 'timecode');
  box(10, FA);
  m.prop(F.fridgeShelf(6), 12, FA); // 12–17, верх 40
  box(14, 40);
  tc(15, 37);
  tc(16, 37);

  // Экран 1 (16–31): ящики «2007» вплотную к полке, вторая полка со стопкой ящиков, телефон.
  m.prop(F.crates2007(3, 3), 18, FA); // 18–20, верх 40
  snow(19, 40, 20);
  tc(21, 40);
  tc(22, 40);
  m.prop(F.fridgeShelf(6), 23, FA); // 23–28, верх 40
  box(27, 40);
  box(27, 39);
  snow(24, 40);
  enemy('phone', 31, FA);

  // Экран 2 (32–47): морозильные блоки, короткая труба с сосулькой, таймкоды над ней.
  tc(32, FA);
  m.prop(F.freezerUnit(4), 33, FA); // 33–36, верх 41
  pipe(37, 5, 39, 1); // 37–41, верх 39
  icicle(40, 39);
  tc(38, 36);
  tc(40, 36);
  snow(39, 39);
  m.prop(F.freezerUnit(4), 42, FA); // 42–45, верх 41
  pair(46, FA, 'coffee', null);
  enemy('phone', 45, 41);

  // ——— Экран 3 (48–63) — низ шахты B: большой ящик, ящики «2007», трубы вверх ———
  m.prop(F.bigCrate(4, 3), 48, FA); // 48–51, верх 40
  m.prop(F.crates2007(12, 2), 52, FA); // 52–63, верх 41
  m.point('respawn', 53, 41); // B

  // B. Подъём: трубы лесенкой, ферма посередине (как в оригинале), стопки ящиков.
  pipe(55, 8, 39, 5); // P1 55–62
  pipe(48, 7, 37); // P2 48–54
  tc(50, 36);
  girder(52, 12, 35); // G1 52–63 — пролёт слева свободен
  m.prop(F.cans(4), 59, 35); // банки на ферме, верх 33
  tc(54, 34);
  tc(55, 34);
  pipe(48, 8, 33, 2); // P3 48–55
  icicle(51, 33);
  pipe(56, 8, 31, 3); // P4 56–63
  box(62, 31);
  box(62, 30);
  tc(58, 29);
  pipe(48, 7, 29); // P5 48–54
  icicle(53, 29);
  snow(49, 29);
  // Звезда — над тающим диском: встал, подпрыгнул, пока лёд держит.
  melt(48, 27, 'cd'); // 48–49, верх 27
  m.point('pickup', 49, 25, { kind: 'star' });
  girder(55, 9, 27); // G2 55–63
  m.prop(F.cans(4), 60, 27); // верх 25 — ступенька на верхний ярус

  // ——— C. Верхний ярус, экран 1 (64–79): морозильный блок, труба с сосулькой, телефон ———
  m.point('respawn', 58, 27); // C (на ферме G2 — видна в начале сегмента)
  m.prop(F.freezerUnit(4), 66, FC); // 66–69, верх 22
  tc(70, FC);
  pipe(71, 5, 20, 2); // 71–75
  icicle(73, 20);
  tc(72, 17);
  tc(74, 17);
  pair(76, FC, null, 'coffee');
  enemy('phone', 79, FC);

  // Экран 2 (80–95): банки, яма-шахта с тающим плеером, ящики «2007», труба с сосульками.
  m.prop(F.cans(4), 80, FC); // 80–83, верх 22
  melt(85, FC, 'player'); // 85–86 посреди ямы 84–88
  tc(85, 21);
  tc(86, 21);
  m.prop(F.crates2007(3, 2), 89, FC); // 89–91, верх 22
  snow(90, 22);
  pipe(90, 6, 19, 3); // 90–95
  icicle(92, 19);
  icicle(94, 19);
  enemy('phone', 95, FC);

  // ——— Экран 3 (96–111) — низ шахты D: уступ-ферма, шахта, башня из ящиков ———
  girder(96, 5, FC); // 96–100 — уступ над шахтой
  m.prop(F.cans(3), 96, FC); // 96–98, верх 22
  box(99, FC);
  melt(102, FC, 'cd'); // 102–103 посреди шахты 101–104
  m.prop(F.crates2007(7, 6), 105, FC + 6); // 105–111, верх 24
  snow(106, FC, 20);
  m.point('respawn', 97, 22); // D — на банках

  // D. Трубы зигзагом вверх к проёму вентиляции.
  pipe(100, 7, 22, 4); // Q1 100–106
  pipe(105, 7, 20); // Q2 105–111
  pipe(97, 7, 18, 2); // Q3 97–103
  icicle(99, 18);
  tc(98, 15);
  pipe(105, 6, 16); // Q4 105–110
  pipe(97, 7, 14); // Q5 97–103
  icicle(101, 14);
  pipe(105, 7, 12, 1); // Q6 105–111
  box(109, 12);
  box(110, 12);
  box(109, 11);
  box(110, 11);
  tc(107, 9);
  pipe(97, 7, 10); // Q7 97–103
  snow(98, 10);
  pipe(104, 8, 8); // Q8 104–111
  F.placeExitVent(m, 108, 5); // 108–110, строки 5–7, низ — на Q8

  // ——— Камера ———
  m.segment('right', 0, y(30), 64 * TILE, 15 * TILE);
  m.segment('up', 48 * TILE, y(15), 16 * TILE, 30 * TILE);
  m.segment('right', 48 * TILE, y(15), 64 * TILE, 15 * TILE);
  m.segment('up', 96 * TILE, 0, 16 * TILE, 30 * TILE);
  return m;
}
