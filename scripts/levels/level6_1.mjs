// Уровень 6 «Часовая башня» — по разбору ROM оригинала (docs/refs/level6/LEVEL6_CLOCK_TOWER.md,
// карта docs/refs/level6/map_6.png). Одна часть на 13 экранов, путь лесенкой снизу слева вверх
// направо: 2 экрана вправо (0–2), шахта вверх (2–6), мост вправо (6–8), шахта вверх (8–11),
// финал вправо (11–12) — три цепи над пропастью и выход.
//
// Высоты уступов, места цепей, врагов, ящиков и таймкодов — из таблицы «Уровень по экранам».
// Отступление: прыжок у нас ~40 px (ТЗ), а уступы оригинала идут через 64 px, поэтому между ними
// добавлены латунные трубы-ступени (в оригинале такие полосатые трубы есть на фоне) — каждый
// подъём не выше 32 px. Цепи сдвинуты по высоте так, чтобы на них можно было запрыгнуть.
// Все уступы — oneway (встать сверху, пройти снизу); сплошной только пол экранов 0–2.
import { placers } from './common.mjs';
import * as A from './clock-art.mjs';
import { MapBuilder, TILE } from './lib.mjs';

/** Экран оригинала → (колонка, строка) экрана на карте 6×8 экранов. */
const SCREENS = {
  0: [0, 7],
  1: [1, 7],
  2: [2, 7],
  3: [2, 6],
  4: [2, 5],
  5: [2, 4],
  6: [2, 3],
  7: [3, 3],
  8: [4, 3],
  9: [4, 2],
  10: [4, 1],
  11: [4, 0],
  12: [5, 0],
};
const SW = 16;
const SH = 15;

export function buildLevel6Tower() {
  const m = new MapBuilder(6 * SW, 8 * SH);
  const { box } = placers(m);
  // Экранные координаты → карта: тайлы и пиксели.
  const gc = (n, c) => SCREENS[n][0] * SW + c;
  const gr = (n, r) => SCREENS[n][1] * SH + r;
  const gx = (n, x) => SCREENS[n][0] * SW * TILE + x;
  const gy = (n, y) => SCREENS[n][1] * SH * TILE + y;

  const slabs = [];
  const pipes = [];
  /** Серая плита-уступ оригинала: верх на строке r экрана n, колонки c0..c1. */
  const slab = (n, r, c0, c1) => {
    m.oneway(gc(n, c0), gc(n, c1), gr(n, r));
    slabs.push([gx(n, c0 * TILE), gy(n, r * TILE), (c1 - c0 + 1) * TILE]);
  };
  /** Латунная труба-ступень (наша добавка между уступами оригинала). */
  const pipe = (n, r, c0, c1) => {
    m.oneway(gc(n, c0), gc(n, c1), gr(n, r));
    pipes.push([gx(n, c0 * TILE), gy(n, r * TILE), (c1 - c0 + 1) * TILE]);
  };
  const floor = (n, c0, c1) => {
    m.solid(gc(n, c0), gc(n, c1), gr(n, 12), gr(n, 14));
    slabs.push([gx(n, c0 * TILE), gy(n, 12 * TILE), (c1 - c0 + 1) * TILE, 48]);
  };
  const chains = [];
  /** Цепь: нижний правый угол пути (x, y экрана), размер петли, фаза. */
  const chain = (n, x, y, w, h, phase = 0) => {
    m.pointPx('chain', gx(n, x), gy(n, y), { w, h, phase });
    chains.push([gx(n, x - w), gy(n, y - h), gx(n, x), gy(n, y)]);
  };
  const B = (n, c, r, contains) => box(gc(n, c), gr(n, r), contains);
  /** Блок 2×2: c, c+1 на поверхности r; inLeft / inRight — таймкоды в левом / правом столбике. */
  const block = (n, c, r, { left = null, right = null } = {}) => {
    for (const [cc, k] of [
      [c, left],
      [c + 1, right],
    ]) {
      B(n, cc, r, k);
      B(n, cc, r - 1, k);
    }
  };
  const tc = (n, c, r) => m.point('pickup', gc(n, c), gr(n, r), { kind: 'timecode' });
  const E = (n, kind, c, r) => m.point('enemy', gc(n, c), gr(n, r), { kind });
  const respawn = (n, c, r) => m.point('respawn', gc(n, c), gr(n, r));

  // ——— Экран 0: старт; полка под потолком, пол, два блока ящиков с таймкодами ———
  m.point('spawn', gc(0, 2), gr(0, 12));
  respawn(0, 2, 12);
  floor(0, 0, 15);
  slab(0, 6, 0, 15);
  block(0, 8, 12, { right: 'timecode' });
  block(0, 14, 12, { left: 'timecode' });

  // ——— Экран 1: вертикальная цепь на высокую плиту; крот на полке слева, крыса на полу ———
  floor(1, 0, 15);
  slab(1, 6, 0, 1);
  slab(1, 4, 10, 13);
  E(1, 'mole', 0, 6);
  chain(1, 92, 168, 24, 124);
  tc(1, 8, 2);
  tc(1, 9, 2);
  E(1, 'rat', 14, 12);

  // ——— Экран 2: низ шахты 1. Пол слева, справа пропасть; уступы 128 → 64 → 0 ———
  respawn(2, 2, 12);
  floor(2, 0, 7);
  B(2, 1, 12);
  B(2, 2, 12);
  B(2, 3, 12, 'timecode');
  B(2, 4, 12);
  for (const [c, r] of [
    [0, 3],
    [1, 3],
    [0, 4],
    [1, 4],
  ])
    tc(2, c, r);
  pipe(2, 10, 5, 7);
  slab(2, 8, 6, 11);
  for (const c of [8, 10, 12]) tc(2, c, 6);
  pipe(2, 6, 4, 6);
  slab(2, 4, 8, 15);
  E(2, 'mole', 14, 4);
  pipe(2, 2, 11, 13);
  slab(2, 0, 4, 9);

  // ——— Экран 3: шахта 1. Длинная горизонтальная цепь, крот слева, крыса наверху ———
  block(3, 4, 15, { right: 'timecode' }); // на стыке с экраном 2 — ступень наверх
  pipe(3, 14, 1, 2);
  slab(3, 12, 0, 3);
  chain(3, 208, 176, 124, 24);
  tc(3, 8, 8);
  tc(3, 8, 10);
  pipe(3, 8, 13, 15);
  slab(3, 6, 10, 15);
  slab(3, 4, 0, 7);
  E(3, 'mole', 2, 4);
  pipe(3, 2, 0, 2);
  slab(3, 0, 4, 15);
  block(3, 6, 0, { left: 'timecode' });
  E(3, 'rat', 14, 0);

  // ——— Экран 4: шахта 1. Короткая горизонтальная цепь, врагов нет ———
  pipe(4, 14, 10, 11);
  slab(4, 12, 12, 15);
  pipe(4, 10, 8, 10);
  slab(4, 8, 10, 15);
  chain(4, 112, 112, 91, 24);
  tc(4, 5, 6);
  tc(4, 5, 8);
  pipe(4, 4, 1, 3);
  slab(4, 2, 0, 3);
  block(4, 0, 2);
  slab(4, 0, 5, 5);
  slab(4, 0, 8, 13);

  // ——— Экран 5: шахта 1. Длинная цепь под самым верхом, ряд таймкодов на её пути ———
  pipe(5, 13, 5, 7);
  slab(5, 11, 8, 15);
  E(5, 'mole', 14, 11);
  slab(5, 9, 2, 7);
  pipe(5, 7, 9, 11);
  slab(5, 5, 4, 9);
  slab(5, 4, 12, 15);
  chain(5, 176, 32, 124, 24);
  for (const c of [3, 5, 7]) tc(5, c, 2);

  // ——— Экран 6: верх шахты 1 → мост; крыса на широкой плите ———
  pipe(6, 14, 4, 6);
  slab(6, 12, 0, 3);
  pipe(6, 11, 4, 5);
  slab(6, 9, 2, 7);
  pipe(6, 8, 8, 9);
  slab(6, 6, 0, 10);
  slab(6, 5, 11, 11);
  slab(6, 6, 12, 15);
  respawn(6, 13, 6);
  E(6, 'rat', 7, 6);
  for (const r of [4, 6]) tc(6, 14, r);
  for (const r of [3, 5, 10, 12]) tc(6, 2, r);

  // ——— Экран 7: мост. Две вертикальные цепи над провалом ———
  slab(7, 6, 0, 2);
  slab(7, 5, 3, 3);
  slab(7, 12, 0, 3);
  slab(7, 12, 12, 15);
  block(7, 2, 12, { left: 'timecode', right: 'timecode' });
  chain(7, 124, 176, 24, 124);
  chain(7, 188, 176, 24, 124, 0.5);
  for (const c of [8, 12]) for (const r of [5, 7]) tc(7, c, r);
  for (const r of [1, 3, 5]) tc(7, 15, r);
  tc(7, 0, 7);
  tc(7, 0, 9);

  // ——— Экран 8: мост → низ шахты 2: мелкие уступы, врагов нет ———
  respawn(8, 12, 12);
  slab(8, 12, 2, 7);
  slab(8, 12, 10, 15);
  pipe(8, 10, 8, 9);
  tc(8, 8, 9);
  tc(8, 9, 9);
  slab(8, 8, 12, 15);
  slab(8, 6, 4, 9);
  tc(8, 5, 2);
  tc(8, 5, 4);
  slab(8, 4, 12, 15);
  pipe(8, 2, 8, 10);
  slab(8, 0, 3, 7);

  // ——— Экран 9: шахта 2. Короткая цепь, крот, столбик ящиков; первый жёлудь (кофе) ———
  // На стыке с экраном 8 (на его верхней плите, слева — справа приходит игрок).
  block(9, 3, 15, { right: 'timecode' });
  B(9, 5, 15, 'coffee');
  B(9, 5, 14, 'timecode');
  pipe(9, 13, 8, 9);
  slab(9, 11, 10, 15);
  E(9, 'mole', 12, 11);
  chain(9, 112, 144, 91, 24);
  pipe(9, 6, 0, 2);
  tc(9, 0, 5);
  tc(9, 0, 6);
  slab(9, 4, 0, 3);
  slab(9, 4, 10, 15);
  for (const r of [4, 3, 2]) B(9, 14, r);
  slab(9, 2, 4, 9);
  slab(9, 0, 10, 15);

  // ——— Экран 10: шахта 2. Второй жёлудь на стыке, крот наверху ———
  block(10, 12, 15);
  B(10, 15, 15, 'coffee');
  B(10, 15, 14);
  pipe(10, 13, 8, 9);
  slab(10, 11, 0, 11);
  tc(10, 0, 11);
  tc(10, 2, 11);
  tc(10, 6, 10);
  tc(10, 8, 10);
  pipe(10, 9, 9, 10);
  slab(10, 7, 3, 8);
  pipe(10, 5, 7, 9);
  slab(10, 4, 0, 5);
  slab(10, 4, 10, 15);
  E(10, 'mole', 2, 4);
  pipe(10, 2, 4, 6);
  tc(10, 6, 1);
  tc(10, 8, 1);
  slab(10, 0, 0, 3);

  // ——— Экран 11: верх шахты 2, лесенка узких уступов к финалу ———
  pipe(11, 13, 4, 5);
  slab(11, 12, 2, 7);
  slab(11, 14, 8, 11);
  tc(11, 2, 12);
  pipe(11, 10, 8, 9);
  slab(11, 8, 0, 5);
  respawn(11, 3, 8);
  E(11, 'mole', 2, 8);
  tc(11, 2, 8);
  tc(11, 3, 6);
  slab(11, 6, 8, 9);
  slab(11, 5, 11, 13);

  // ——— Экран 12: пола нет — три вертикальные цепи над пропастью, выход справа ———
  chain(12, 28, 176, 24, 124, 0);
  chain(12, 92, 192, 24, 124, 0.33);
  chain(12, 156, 176, 24, 124, 0.66);
  tc(12, 2, 3);
  tc(12, 3, 3);
  tc(12, 6, 3);
  tc(12, 7, 3);
  tc(12, 12, 2);
  tc(12, 12, 4);
  slab(12, 6, 12, 15);
  m.zone('exit', gx(12, 224), gy(12, 64), 32, 32);

  // ——— Арт ———
  m.paint((p) => {
    A.wall(p, 0, 0, m.cols * TILE, m.rows * TILE);
    // Окна с небом — где они на карте оригинала.
    for (const [n, x, y, w, h] of [
      [1, 0, 16, 32, 64],
      [2, 32, 32, 48, 112],
      [6, 0, 0, 48, 64],
      [6, 112, 0, 48, 80],
      [6, 208, 0, 48, 80],
      [8, 96, 32, 48, 96],
      [9, 16, 32, 32, 96],
      [9, 176, 64, 48, 80],
      [10, 192, 0, 64, 64],
      [11, 192, 128, 64, 112],
      [12, 208, 0, 48, 48],
    ])
      A.window(p, gx(n, x), gy(n, y), w, h);
    // Зелёные трубы фона.
    for (const [n, x] of [
      [0, 80],
      [0, 176],
      [1, 192],
      [2, 112],
      [3, 32],
      [3, 208],
      [4, 176],
      [5, 96],
      [5, 176],
      [6, 64],
      [7, 144],
      [7, 224],
      [8, 160],
      [9, 112],
      [10, 64],
      [10, 128],
      [11, 96],
      [12, 112],
    ])
      A.pipeV(p, gx(n, x), gy(n, 0), gy(n, 240));
    for (const [n, y] of [
      [0, 40],
      [3, 40],
      [4, 152],
      [5, 120],
      [6, 216],
      [8, 168],
      [9, 168],
      [10, 136],
      [11, 40],
    ])
      A.pipeH(p, gx(n, 0), gx(n, 256), gy(n, y));
  });
  m.decor((p) => {
    // Шестерни — на концах петли: у вертикальной сверху и снизу, у горизонтальной слева и справа.
    for (const [x0, y0, x1, y1] of chains) {
      A.chainLoop(p, x0, y0, x1, y1);
      const cx = (x0 + x1) / 2;
      const cy = (y0 + y1) / 2 + 4;
      if (y1 - y0 > x1 - x0) {
        A.gear(p, cx, y0 + 16);
        A.gear(p, cx, y1 - 8);
      } else {
        A.gear(p, x0 + 12, cy);
        A.gear(p, x1 - 12, cy);
      }
    }
    for (const [x, y, w, h] of slabs) A.slab(p, x, y, w, h ?? TILE);
    for (const [x, y, w] of pipes) A.brassPipe(p, x, y, w);
  });

  // ——— Камера ———
  const seg = (dir, n0, n1) => {
    const [c0, r0] = SCREENS[n0];
    const [c1, r1] = SCREENS[n1];
    const x = Math.min(c0, c1) * SW * TILE;
    const y = Math.min(r0, r1) * SH * TILE;
    const w = (Math.abs(c1 - c0) + 1) * SW * TILE;
    const h = (Math.abs(r1 - r0) + 1) * SH * TILE;
    m.segment(dir, x, y, w, h);
  };
  seg('right', 0, 2);
  seg('up', 2, 6);
  seg('right', 6, 8);
  seg('up', 8, 11);
  seg('right', 11, 12);
  return m;
}
