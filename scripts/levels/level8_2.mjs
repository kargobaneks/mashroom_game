// Уровень 8, часть 8-2 «Складные платформы» — по разбору ROM оригинала
// (docs/refs/level8/LEVEL8_FUTURE_WORLD.md, карта docs/refs/level8/map_8-2.png): 7 экранов
// вправо. Крысы с рогатками (4), на экране 4 — пропасть и 4 складные платформы лесенкой вверх
// (без врагов), пятая — на экране 5. 16 ящиков (3 с таймкодом, 1 с кофе — жёлудь оригинала).
//
// Отступления: под трубками оригинала (через 64 px над полом) — решётка-ступень; пропасть
// экрана 2 сужена до 48 px; ящики и таймкоды, висевшие в воздухе, — на опоре. Невидимый
// объект 22 не ставим (его роль не установлена). Два сегмента камеры: с экрана 3 — контрольная
// точка перед пропастью.
import { futureKit } from './future-kit.mjs';
import { MapBuilder } from './lib.mjs';

const SCREENS = Object.fromEntries(Array.from({ length: 7 }, (_, i) => [i, [i, 0]]));

export function buildLevel8Folds() {
  const m = new MapBuilder(7 * 16, 15);
  const k = futureKit(m, SCREENS);
  const { wall, pipe, tube, grate, box, tc, enemy } = k;

  // ——— Экран 0: ступень-блок, ряд из 4 ящиков ———
  m.point('spawn', k.gc(0, 2), k.gr(0, 14));
  k.respawn(0, 2, 14);
  wall(0, 0, 15, 0, 2);
  wall(0, 0, 3, 3, 4);
  wall(0, 4, 11, 3, 7);
  wall(0, 12, 15, 3, 3);
  wall(0, 0, 5, 14, 14);
  wall(0, 6, 15, 12, 14);
  for (const c of [10, 11, 12, 13]) box(0, c, 12, c === 12 ? 'timecode' : null);

  // ——— Экран 1: крысы с рогатками, трубки и труба над пропастью, блок 2×2 с кофе ———
  wall(1, 0, 15, 0, 3);
  wall(1, 0, 3, 12, 14);
  wall(1, 8, 15, 14, 14);
  grate(1, 10, 0, 1);
  tube(1, 8, 0, 3);
  tube(1, 6, 0, 3);
  pipe(1, 8, 4, 10);
  box(1, 6, 8);
  box(1, 7, 8);
  k.block2(1, 8, 14, [null, null, 'timecode', 'coffee']);
  enemy(1, 'slingRat', 2, 12);
  enemy(1, 'slingRat', 14, 14);
  k.pink(1, 1, 9, 11);
  for (const r of [11, 12, 13]) tc(1, 14, r);

  // ——— Экран 2: пропасть 48 px, стопка ящиков ———
  wall(2, 0, 15, 0, 3);
  wall(2, 0, 4, 12, 14);
  wall(2, 8, 15, 12, 14);
  pipe(2, 6, 4, 15);
  box(2, 12, 12, 'timecode');
  box(2, 12, 11);

  // ——— Экран 3: крыса на трубках, ящики на трубе и на полу ———
  wall(3, 0, 15, 0, 3);
  wall(3, 0, 3, 12, 14);
  wall(3, 8, 15, 14, 14);
  grate(3, 10, 0, 1);
  tube(3, 8, 0, 3);
  tube(3, 6, 0, 3);
  pipe(3, 8, 4, 10);
  box(3, 6, 8);
  box(3, 7, 8);
  box(3, 8, 14);
  box(3, 9, 14);
  enemy(3, 'slingRat', 3, 6);
  tc(3, 8, 8);
  tc(3, 10, 8);
  k.pink(3, 1, 9, 11);

  // ——— Экран 4: пропасть, 4 складные платформы лесенкой вверх ———
  wall(4, 0, 3, 0, 7);
  wall(4, 4, 7, 0, 6);
  wall(4, 8, 11, 0, 5);
  wall(4, 12, 15, 0, 4);
  for (const [x, y] of [
    [56, 208],
    [120, 192],
    [184, 176],
    [248, 160],
  ])
    k.fold(4, x, y);

  // ——— Экран 5: столб, крыса, пятая складная платформа, уступ ———
  wall(5, 0, 13, 0, 3);
  wall(5, 14, 15, 0, 5);
  wall(5, 2, 4, 10, 14);
  enemy(5, 'slingRat', 4, 10);
  k.fold(5, 112, 144);
  wall(5, 8, 15, 8, 14);
  tc(5, 3, 8);
  tc(5, 4, 8);

  // ——— Экран 6: уступ под низким потолком, спуск к выходу ———
  wall(6, 0, 15, 0, 5);
  wall(6, 0, 11, 8, 14);
  wall(6, 12, 15, 14, 14);
  k.exit(6, 14);

  k.finish();
  m.segment('right', 0, 0, 4 * 256, 240);
  m.segment('right', 3 * 256, 0, 4 * 256, 240);
  k.respawn(3, 1, 12);
  return m;
}
