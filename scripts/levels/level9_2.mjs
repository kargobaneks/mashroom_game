// Уровень 9, часть 9-2 «Леса с висящими платформами» — по разбору ROM оригинала
// (docs/refs/level9/LEVEL9_FATCAT_LAIR.md, карта docs/refs/level9/map_9-2.png): 7 экранов
// вправо. Внизу — сплошная ферма-пол (пропастей нет), над ней — блоки-стойки лесов и висящие
// полосатые платформы. На каждом экране, кроме первого, у правого края — точка вылета птиц
// (у нас — заголовки уровня 2), на экране 5 — птица с «яйцом». 14 ящиков (1 с таймкодом,
// 1 с кофе — жёлудь оригинала): ящик с таймкодом — перед первой птицей.
//
// Отступления: подъёмы не выше 32 px; висящие платформы опущены на высоту прыжка.
// Контрольная точка — экран 4.
import { lairKit } from './lair-kit.mjs';
import { MapBuilder } from './lib.mjs';

const SCREENS = Object.fromEntries(Array.from({ length: 7 }, (_, i) => [i, [i, 0]]));

export function buildLevel9Scaffold() {
  const m = new MapBuilder(7 * 16, 15);
  const k = lairKit(m, SCREENS);
  const { wall, pipe, box, tc } = k;

  // Ферма-пол во всю длину.
  for (let n = 0; n < 7; n++) wall(n, 0, 15, 13, 14);

  // ——— Экран 0: стойка, висящая платформа ———
  m.point('spawn', k.gc(0, 2), k.gr(0, 13));
  k.respawn(0, 2, 13);
  wall(0, 8, 10, 11, 12);
  k.hanger(0, 9, 12, 14);
  k.pink(0, 3, 0, 12);
  tc(0, 12, 8);
  tc(0, 14, 8);

  // ——— Экран 1: две стойки, стопка (нижний — с таймкодом), первая птица ———
  wall(1, 4, 7, 11, 12);
  wall(1, 10, 15, 9, 12);
  box(1, 11, 9, 'timecode');
  box(1, 11, 8);
  k.nest(1, 4);
  k.hanger(1, 9, 1, 2);
  tc(1, 2, 8);

  // ——— Экран 2: висящие платформы лесенкой ———
  k.hanger(2, 10, 2, 4);
  k.hanger(2, 9, 8, 10);
  k.nest(2, 6);
  tc(2, 3, 9);
  tc(2, 9, 8);
  tc(2, 13, 12);

  // ——— Экран 3: платформа, пара ящиков на полу, стойка ———
  k.hanger(3, 11, 3, 5);
  box(3, 10, 13);
  box(3, 11, 13);
  wall(3, 13, 15, 11, 12);
  k.nest(3, 4);
  tc(3, 4, 10);

  // ——— Экран 4: генераторы, белая труба; стопка с кофе, пары ящиков ———
  k.generator(4, 4, 13);
  k.generator(4, 10, 13);
  pipe(4, 9, 4, 12);
  box(4, 2, 13, 'coffee');
  box(4, 2, 12);
  box(4, 7, 9);
  box(4, 8, 9);
  box(4, 14, 13);
  box(4, 15, 13);
  k.nest(4, 6);
  tc(4, 5, 9);
  tc(4, 11, 9);

  // ——— Экран 5: стойки, платформа, птица с «яйцом» ———
  wall(5, 2, 3, 11, 12);
  wall(5, 9, 10, 11, 12);
  k.hanger(5, 9, 5, 7);
  box(5, 12, 13);
  box(5, 13, 13);
  k.nest(5, 4, true);
  tc(5, 6, 8);
  tc(5, 9, 10);

  // ——— Экран 6: длинная труба с парой ящиков, выход ———
  k.generator(6, 1, 13);
  pipe(6, 9, 3, 13);
  box(6, 8, 9);
  box(6, 9, 9);
  k.nest(6, 4);
  for (const c of [4, 5, 11, 12]) tc(6, c, 8);
  k.exit(6, 13);

  k.finish();

  m.segment('right', 0, 0, 5 * 256, 240);
  m.segment('right', 4 * 256, 0, 3 * 256, 240);
  k.respawn(4, 1, 13);
  return m;
}
