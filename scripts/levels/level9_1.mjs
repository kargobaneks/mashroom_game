// Уровень 9, часть 9-1 «Цех с конвейерами» — по разбору ROM оригинала
// (docs/refs/level9/LEVEL9_FATCAT_LAIR.md, карта docs/refs/level9/map_9-1.png):
// 8 экранов — 0–4 вправо, 5 вверх, 6–7 вправо. Генераторы и труба с ящиками (0), крыса с
// рогаткой на трубе (1), два конвейера с рычагами — у каждого ящик-«патрон» (2–3), подъём
// по трубам зигзагом; прямой путь справа перекрыт блоком ящиков 2×2 (4–5), две засады сразу
// после подъёма (6), выход наверху справа (7). 18 ящиков (1 с таймкодом).
//
// Отступления (уроки уровней 6–8): подъёмы не выше 32 px — трубы опущены, генераторы 32 px
// (в оригинале 48); полки подъёма — через 32 px (в оригинале через 48–64); таймкоды, висевшие
// выше прыжка, опущены. Контрольная точка — у первого конвейера (экран 2).
import { lairKit } from './lair-kit.mjs';
import { MapBuilder } from './lib.mjs';

/** Экран оригинала → (колонка, строка) экрана на карте 7×2. */
const SCREENS = {
  0: [0, 1],
  1: [1, 1],
  2: [2, 1],
  3: [3, 1],
  4: [4, 1],
  5: [4, 0],
  6: [5, 0],
  7: [6, 0],
};

export function buildLevel9Conveyors() {
  const m = new MapBuilder(7 * 16, 2 * 15);
  const k = lairKit(m, SCREENS);
  const { wall, pipe, tube, box, tc, enemy } = k;

  // ——— Экран 0: два генератора, труба с парой ящиков, крюк на цепи ———
  m.point('spawn', k.gc(0, 2), k.gr(0, 12));
  k.respawn(0, 2, 12);
  wall(0, 0, 15, 12, 14);
  k.generator(0, 4, 12);
  k.generator(0, 11, 12);
  pipe(0, 8, 4, 12);
  box(0, 8, 8);
  box(0, 9, 8);
  k.hook(0, 2, 0, 8);
  k.pink(0, 14, 0, 11);
  tc(0, 14, 10);
  tc(0, 15, 10);

  // ——— Экран 1: крыса с рогаткой на средней трубе, стопка (нижний — с таймкодом) ———
  wall(1, 0, 15, 12, 14);
  pipe(1, 8, 0, 3);
  pipe(1, 10, 5, 13);
  pipe(1, 8, 10, 15);
  box(1, 3, 12, 'timecode');
  box(1, 3, 11);
  enemy(1, 'slingRat', 12, 10);
  for (const [c, r] of [
    [6, 8],
    [7, 7],
    [8, 7],
    [9, 8],
  ])
    tc(1, c, r);

  // ——— Экран 2: уступ с рычагом и ящиком-«патроном», конвейер ———
  wall(2, 0, 3, 10, 14);
  box(2, 0, 10);
  k.lever(2, 2, 10);
  k.conveyor(2, 10, 4, 15);
  for (const c of [5, 7, 9, 11]) tc(2, c, 8);
  for (const c of [6, 8, 10, 12]) tc(2, c, 7);

  // ——— Экран 3: крыса у рычага, второй конвейер ———
  wall(3, 0, 3, 10, 14);
  box(3, 0, 10);
  k.lever(3, 2, 10);
  enemy(3, 'slingRat', 1, 10);
  k.conveyor(3, 10, 4, 15);
  for (const c of [6, 8, 10, 12]) tc(3, c, 8);

  // ——— Экран 4: крыса на полке, подъём зигзагом; справа наверху — блок ящиков 2×2 ———
  wall(4, 0, 15, 10, 14);
  tube(4, 8, 11, 15);
  enemy(4, 'slingRat', 14, 8);
  pipe(4, 6, 6, 10);
  tube(4, 4, 1, 5);
  pipe(4, 2, 6, 15);
  k.block2(4, 14, 2);
  tube(4, 0, 1, 5);
  k.pink(4, 0, 5, 9);

  // ——— Экран 5 (вверх): средняя труба, верхняя левая, выход вправо по трубе ———
  pipe(5, 13, 6, 10);
  tube(5, 11, 1, 5);
  box(5, 1, 11);
  box(5, 1, 10);
  pipe(5, 9, 6, 15);
  k.pink(5, 12, 0, 8);
  tc(5, 3, 9);
  tc(5, 8, 11);
  tc(5, 12, 7);

  // ——— Экран 6: две засады — на полу и на верхней трубе; пара ящиков на трубе ———
  wall(6, 0, 15, 12, 14);
  pipe(6, 9, 0, 2);
  pipe(6, 10, 4, 12);
  box(6, 5, 10);
  box(6, 6, 10);
  pipe(6, 8, 11, 15);
  enemy(6, 'ambushRat', 4, 12);
  enemy(6, 'ambushRat', 12, 8);
  for (const [c, r] of [
    [1, 8],
    [8, 9],
    [9, 9],
    [10, 9],
    [13, 7],
    [14, 7],
    [3, 11],
  ])
    tc(6, c, r);

  // ——— Экран 7: генератор со стопкой, пара на полу, выход наверху справа ———
  wall(7, 0, 15, 12, 14);
  k.generator(7, 1, 12);
  box(7, 2, 10);
  box(7, 2, 9);
  box(7, 6, 12);
  box(7, 7, 12);
  k.generator(7, 8, 12);
  tube(7, 8, 12, 15);
  k.hook(7, 5, 0, 7);
  tc(7, 9, 9);
  tc(7, 13, 7);
  k.exit(7, 8);

  k.finish();

  // Контрольная точка у первого конвейера: второй сегмент начинается с экрана 2.
  m.segment('right', 0, 240, 3 * 256, 240);
  m.segment('right', 2 * 256, 240, 3 * 256, 240);
  k.respawn(2, 1, 10);
  m.segment('up', 4 * 256, 0, 256, 480);
  k.respawn(4, 2, 10);
  m.segment('right', 4 * 256, 0, 3 * 256, 240);
  k.respawn(5, 8, 9);
  return m;
}
