// Уровень 8, часть 8-3 «Магнит и механические псы» — по разбору ROM оригинала
// (docs/refs/level8/LEVEL8_FUTURE_WORLD.md, карта docs/refs/level8/map_8-3.png): 6 экранов
// вправо. 5 механических псов, металлический блок на конце трубы (экран 2), магнит (экран 3)
// и звезда-жизнь в нише справа от него. 16 ящиков (5 с таймкодом).
//
// Магнит — по ТЗ (решение пользователя 17.11): герой с металлическим блоком в руках под
// магнитом поднимается, пока блок не упрётся в магнит, и висит; прыжок — блок прилипает,
// герой отталкивается и долетает до ниши со звездой. С пола (80 px) и с блока на полу
// (64 px) до ниши не допрыгнуть. Конвейер на полке ниши не делали (в оригинале честного
// пути к звезде не нашли, у нас путь — через магнит).
// Отступления: ящики и таймкоды, висевшие в воздухе, — на опоре; под трубами — решётка-ступень.
// Два сегмента камеры: с экрана 2 — контрольная точка (блок и ящики возвращаются на место).
import { futureKit } from './future-kit.mjs';
import { MapBuilder } from './lib.mjs';

const SCREENS = Object.fromEntries(Array.from({ length: 6 }, (_, i) => [i, [i, 0]]));

export function buildLevel8Magnet() {
  const m = new MapBuilder(6 * 16, 15);
  const k = futureKit(m, SCREENS);
  const { wall, pipe, tube, grate, box, tc, enemy } = k;

  // ——— Экран 0: ступень, блок 2×2 и стопка ящиков перед первым псом ———
  m.point('spawn', k.gc(0, 1), k.gr(0, 12));
  k.respawn(0, 1, 12);
  wall(0, 0, 15, 0, 1);
  wall(0, 0, 3, 12, 14);
  wall(0, 4, 15, 14, 14);
  k.block2(0, 4, 14);
  pipe(0, 10, 6, 7);
  tube(0, 10, 8, 11);
  tube(0, 8, 8, 11);
  tube(0, 6, 8, 11);
  pipe(0, 8, 12, 15);
  box(0, 7, 10);
  box(0, 7, 9);
  for (const [c, r] of [
    [13, 7],
    [15, 7],
    [14, 5],
    [10, 5],
  ])
    tc(0, c, r);
  k.pink(0, 9, 7, 13);

  // ——— Экран 1: пёс на полу, труба, трубки, пара ящиков ———
  wall(1, 0, 15, 0, 1);
  wall(1, 0, 7, 14, 14);
  wall(1, 10, 15, 14, 14);
  grate(1, 12, 2, 3);
  pipe(1, 10, 4, 9);
  for (const r of [6, 8, 10]) tube(1, r, 10, 13);
  box(1, 6, 10);
  box(1, 7, 10);
  enemy(1, 'mechDog', 2, 14);
  tc(1, 2, 11);
  tc(1, 4, 11);
  k.pink(1, 11, 2, 13);

  // ——— Экран 2: пёс на трубках, стопка с таймкодами, металлический блок на конце трубы ———
  wall(2, 0, 15, 0, 1);
  wall(2, 0, 15, 14, 14);
  pipe(2, 8, 0, 5);
  tube(2, 8, 6, 9);
  tube(2, 10, 6, 9);
  tube(2, 12, 6, 9);
  pipe(2, 12, 10, 13);
  enemy(2, 'mechDog', 7, 8);
  m.point('item', k.gc(2, 13), k.gr(2, 12), { kind: 'metal' });
  box(2, 2, 14, 'timecode');
  box(2, 2, 13, 'timecode');
  for (const [c, r] of [
    [1, 7],
    [3, 7],
    [5, 7],
    [8, 6],
  ])
    tc(2, c, r);

  // ——— Экран 3: магнит под потолком, ниша со звездой справа ———
  wall(3, 0, 15, 0, 5);
  wall(3, 12, 13, 6, 9);
  pipe(3, 9, 9, 11);
  m.point('pickup', k.gc(3, 10), k.gr(3, 9), { kind: 'star' });
  k.magnet(3, 104, 96, 128);
  wall(3, 0, 15, 14, 14);
  tc(3, 2, 11);
  tc(3, 4, 11);
  k.pink(3, 0, 10, 13);

  // ——— Экран 4: два пса, решётка-ступень, труба, трубки, стопка ———
  wall(4, 0, 15, 0, 1);
  wall(4, 0, 7, 14, 14);
  wall(4, 10, 15, 14, 14);
  grate(4, 12, 2, 3);
  pipe(4, 10, 4, 9);
  for (const r of [6, 8, 10]) tube(4, r, 10, 13);
  // Стопка — не вплотную к пропасти: перепрыгнув её, есть где приземлиться.
  box(4, 5, 14, 'timecode');
  box(4, 5, 13);
  enemy(4, 'mechDog', 4, 14);
  enemy(4, 'mechDog', 12, 8);
  k.pink(4, 11, 2, 13);

  // ——— Экран 5: труба с ящиками 2×2, пёс, выход справа на ступени ———
  wall(5, 0, 15, 0, 1);
  wall(5, 0, 9, 12, 14);
  wall(5, 12, 15, 12, 14);
  grate(5, 10, 1, 2);
  pipe(5, 8, 3, 14);
  k.block2(5, 7, 8, [null, null, 'timecode', 'timecode']);
  enemy(5, 'mechDog', 12, 8);
  tc(5, 1, 10);
  tc(5, 3, 10);
  tc(5, 14, 7);
  tc(5, 14, 6);
  k.exit(5, 12);

  k.finish();
  m.segment('right', 0, 0, 3 * 256, 240);
  m.segment('right', 2 * 256, 0, 4 * 256, 240);
  k.respawn(2, 1, 14);
  return m;
}
