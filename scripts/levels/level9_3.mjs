// Уровень 9, часть 9-3 «Лазерный пресс над конвейером» — по разбору ROM оригинала
// (docs/refs/level9/LEVEL9_FATCAT_LAIR.md, карта docs/refs/level9/map_9-3.png): 7 экранов
// вправо. Генераторы (0), два пресса с тремя лазерами над конвейером, у каждого — рычаг
// и ящики-«патроны» (1–2), трубы и три механических пса (4–6), выход на уступе справа.
// 19 ящиков (2 с таймкодом — у входа в зону лазеров).
//
// Лазеры: цикл 241 кадр (120 горит, 121 нет), сдвиг соседних 0 / +4 / +32 (замер). Лента
// сначала тащит назад, под лучи; рычаг (низкий бросок) — и она помогает.
// Отступления: трубы опущены на высоту прыжка; выход — на уступе 32 px (в оригинале 64);
// между рычагом и первым лучом — две клетки твёрдого пола, где можно переждать (лента и лазеры
// сдвинуты на 32 px вправо): иначе лента сразу несёт под луч.
// Контрольная точка — экран 3.
import { lairKit } from './lair-kit.mjs';
import { MapBuilder } from './lib.mjs';

const SCREENS = Object.fromEntries(Array.from({ length: 7 }, (_, i) => [i, [i, 0]]));

export function buildLevel9Press() {
  const m = new MapBuilder(7 * 16, 15);
  const k = lairKit(m, SCREENS);
  const { wall, pipe, tube, grate, box, tc, enemy } = k;

  // ——— Экран 0: два генератора, труба, пара ящиков ———
  m.point('spawn', k.gc(0, 2), k.gr(0, 12));
  k.respawn(0, 2, 12);
  wall(0, 0, 15, 12, 14);
  k.generator(0, 3, 12);
  k.generator(0, 11, 12);
  pipe(0, 8, 3, 13);
  box(0, 7, 12);
  box(0, 8, 12);
  k.hook(0, 7, 0, 6);

  // ——— Экраны 1–2: пресс с тремя лазерами над конвейером, рычаг и «патроны» ———
  for (const n of [1, 2]) {
    wall(n, 0, 5, 12, 14);
    k.lever(n, 3, 12);
    k.conveyor(n, 12, 6, 15);
    k.press(n, 6, 15, 8);
    k.laser(n, 112, 9, 12, 0);
    k.laser(n, 176, 9, 12, 4);
    k.laser(n, 240, 9, 12, 32);
  }
  box(1, 0, 12, 'timecode');
  box(1, 1, 12, 'timecode');
  tc(1, 8, 11);
  tc(1, 12, 11);
  box(2, 1, 12);
  for (const c of [2, 6, 10, 14]) tc(2, c, 11);

  // ——— Экран 3: стопка, уступ с парой ящиков ———
  wall(3, 0, 15, 12, 14);
  wall(3, 9, 15, 10, 11);
  box(3, 4, 12);
  box(3, 4, 11);
  box(3, 10, 10);
  box(3, 11, 10);
  tc(3, 6, 9);
  tc(3, 13, 8);

  // ——— Экран 4: длинная труба со стопкой, пёс на полу ———
  wall(4, 0, 15, 12, 14);
  wall(4, 0, 2, 10, 11);
  tube(4, 8, 0, 3);
  pipe(4, 10, 4, 14);
  box(4, 9, 10);
  box(4, 9, 9);
  enemy(4, 'mechDog', 12, 12);
  for (const c of [5, 6, 7, 11, 12, 13]) tc(4, c, 8);

  // ——— Экран 5: пёс на трубе, пара на полу, стопка на трубе, генератор ———
  wall(5, 0, 15, 12, 14);
  box(5, 2, 12);
  box(5, 3, 12);
  pipe(5, 10, 5, 11);
  enemy(5, 'mechDog', 8, 10);
  box(5, 11, 10);
  box(5, 11, 9);
  k.generator(5, 13, 12);
  for (const c of [5, 6, 13, 14]) tc(5, c, c > 12 ? 9 : 8);

  // ——— Экран 6: генератор, пёс, блок 2×2, выход на уступе ———
  wall(6, 0, 15, 12, 14);
  k.generator(6, 3, 12);
  enemy(6, 'mechDog', 8, 12);
  k.block2(6, 10, 12);
  grate(6, 10, 13, 15);
  tc(6, 4, 9);
  tc(6, 14, 8);
  k.exit(6, 10);

  k.finish();

  m.segment('right', 0, 0, 4 * 256, 240);
  m.segment('right', 3 * 256, 0, 4 * 256, 240);
  k.respawn(3, 1, 12);
  return m;
}
