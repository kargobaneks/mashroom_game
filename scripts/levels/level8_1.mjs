// Уровень 8, часть 8-1 «Завод: давящие блоки» — по разбору ROM оригинала
// (docs/refs/level8/LEVEL8_FUTURE_WORLD.md, карта docs/refs/level8/map_8-1.png):
// 7 экранов — 0–2 вправо, 3–4 вверх (шахта), 5–6 вправо к выходу. Враги — 2 крота и крыса
// (те же, что в часовой башне), в конце — 3 давящих блока. 24 ящика (6 с таймкодом):
// стопки на экране 0, пара на решётке, пара и блок 2×2 на экране 2, колонна 2×4 в шахте.
//
// Отступления (уроки уровней 6–7): подъёмы не выше 32 px — между трубами оригинала (через
// 48–64 px) добавлены решётки-ступени; шахта начинается на экране 2 лесенкой из трубок
// и решёток; пропасть экрана 2 сужена до 48 px. Ящики и таймкоды, висевшие в оригинале
// в воздухе, стоят на ближайшей опоре и на высоте прыжка. Второй давящий блок — над
// пропастью у края экрана 5: перейти можно только по опущенному блоку (как в оригинале).
import { futureKit } from './future-kit.mjs';
import { MapBuilder } from './lib.mjs';

/** Экран оригинала → (колонка, строка) экрана на карте 5×3. */
const SCREENS = { 0: [0, 2], 1: [1, 2], 2: [2, 2], 3: [2, 1], 4: [2, 0], 5: [3, 0], 6: [4, 0] };

export function buildLevel8Factory() {
  const m = new MapBuilder(5 * 16, 3 * 15);
  const k = futureKit(m, SCREENS);
  const { wall, pipe, tube, grate, box, tc, enemy } = k;

  // ——— Экран 0: пол и ступень-блок, две стопки ящиков ———
  m.point('spawn', k.gc(0, 2), k.gr(0, 14));
  k.respawn(0, 2, 14);
  wall(0, 0, 15, 0, 1);
  wall(0, 0, 7, 14, 14);
  wall(0, 8, 15, 12, 14);
  box(0, 10, 12);
  box(0, 10, 11);
  box(0, 14, 12, 'timecode');
  box(0, 14, 11);
  tc(0, 7, 11);
  tc(0, 9, 10);
  k.pink(0, 11, 2, 11);

  // ——— Экран 1: решётка, белая труба и башня из трубок, ящики на решётке ———
  wall(1, 0, 15, 0, 1);
  wall(1, 0, 7, 14, 14);
  wall(1, 10, 15, 14, 14);
  grate(1, 12, 2, 3);
  pipe(1, 10, 4, 9);
  grate(1, 8, 8, 9);
  box(1, 8, 8);
  box(1, 9, 8);
  for (const r of [6, 8, 10]) tube(1, r, 10, 13);
  k.pink(1, 11, 2, 13);
  for (const [c, r] of [
    [1, 11],
    [3, 11],
    [5, 9],
    [7, 9],
    [11, 5],
    [13, 5],
    [14, 13],
  ])
    tc(1, c, r);

  // ——— Экран 2: пропасть, ступень-блок, низ шахты — лесенка из трубок и решёток ———
  wall(2, 0, 1, 14, 14);
  wall(2, 5, 9, 14, 14);
  wall(2, 10, 15, 12, 14);
  box(2, 0, 14);
  box(2, 1, 14);
  grate(2, 10, 10, 11);
  tube(2, 8, 12, 15);
  k.block2(2, 14, 8, [null, null, 'timecode', null]);
  grate(2, 6, 9, 10);
  tube(2, 4, 12, 15);
  pipe(2, 2, 3, 10);
  grate(2, 0, 1, 2);
  k.pink(2, 13, 9, 11);
  for (const [c, r] of [
    [5, 1],
    [7, 1],
    [9, 1],
    [13, 3],
    [10, 5],
    [7, 13],
    [11, 9],
  ])
    tc(2, c, r);

  // ——— Экран 3: шахта. Трубы слева и справа, посередине — стена, колонна из 8 ящиков ———
  grate(3, 13, 3, 4);
  pipe(3, 11, 0, 5);
  grate(3, 9, 3, 4);
  pipe(3, 8, 0, 5);
  grate(3, 6, 2, 3);
  pipe(3, 4, 0, 5);
  wall(3, 6, 9, 4, 11);
  pipe(3, 4, 10, 15);
  pipe(3, 8, 10, 15);
  pipe(3, 11, 10, 15);
  for (const [r, kind] of [
    [11, 'timecode'],
    [10, 'timecode'],
    [9, null],
    [8, null],
  ]) {
    box(3, 11, r, kind);
    box(3, 12, r, kind);
  }
  grate(3, 2, 12, 13);
  grate(3, 0, 14, 15);
  enemy(3, 'mole', 2, 8);
  enemy(3, 'mole', 14, 4);
  k.pink(3, 11, 0, 3);
  for (const [c, r] of [
    [4, 3],
    [4, 2],
    [8, 3],
    [8, 2],
    [8, 1],
    [4, 10],
    [4, 7],
    [13, 3],
    [13, 2],
    [14, 7],
  ])
    tc(3, c, r);

  // ——— Экран 4: верх шахты. Белая труба во всю ширину, крыса, стопка ящиков ———
  wall(4, 0, 15, 0, 3);
  grate(4, 13, 12, 13);
  grate(4, 11, 14, 15);
  grate(4, 9, 12, 13);
  pipe(4, 8, 0, 11);
  box(4, 5, 8);
  box(4, 5, 7);
  enemy(4, 'rat', 9, 8);
  tc(4, 3, 7);
  tc(4, 3, 5);

  // ——— Экран 5: давящие блоки — первый на полу, второй над пропастью у правого края ———
  wall(5, 0, 15, 0, 3);
  wall(5, 0, 3, 4, 5);
  wall(5, 8, 9, 4, 8);
  wall(5, 0, 13, 14, 14);
  k.crusher(5, 5, 14, 4);
  k.crusher(5, 14, 14, 4, 60);
  for (const c of [8, 10, 12]) tc(5, c, 11);

  // ——— Экран 6: стопка ящиков, третий давящий блок, выход ———
  wall(6, 0, 15, 0, 4);
  wall(6, 0, 15, 14, 14);
  wall(6, 1, 2, 12, 13);
  box(6, 4, 14);
  box(6, 4, 13);
  k.crusher(6, 8, 14, 5, 120);
  tc(6, 4, 11);
  tc(6, 6, 11);
  tc(6, 7, 11);
  k.exit(6, 14);

  k.finish();

  m.segment('right', 0, 480, 768, 240);
  m.segment('up', 512, 0, 256, 720);
  m.segment('right', 512, 0, 768, 240);
  k.respawn(2, 6, 14);
  k.respawn(4, 2, 8);
  return m;
}
