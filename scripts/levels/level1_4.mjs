// Уровень 1, часть 1-4: «Подвал» — служебный спуск по трубам и арена Агранович (подвал-обжарочная).
// Сетка 16 × 30: строки 0–14 — шахта (прокрутка вниз), 15–29 — арена (зафиксированный экран).
import * as A from './cafe-art.mjs';
import { placers } from './common.mjs';
import { MapBuilder, TILE } from './lib.mjs';

export function buildLevel1Basement() {
  const m = new MapBuilder(16, 30);
  const { box, tc } = placers(m);
  const AY = 15 * TILE;

  m.paint((p) => {
    A.brickWall(p, 0, 0, 16 * TILE, 30 * TILE, true, 28 * TILE);
    p.rect(0, 0, 10 * TILE, 15 * TILE, 0x000000);
    p.rect(0, AY, 10 * TILE, TILE, 0x000000);
    p.rect(0, AY, TILE, 15 * TILE, 0x000000);
    p.rect(15 * TILE, 0, TILE, 30 * TILE, 0x000000);
  });

  // ——— Шахта ———
  m.solid(0, 9, 0, 14);
  m.solid(15, 15, 0, 29);
  m.point('spawn', 12, 2);
  m.prop(A.pipe(2), 10, 6);
  m.prop(A.pipe(2), 13, 11);
  m.point('respawn', 10, 5);
  for (const r of [3, 7, 9, 13]) tc(12, r);
  tc(10, 5);
  tc(14, 10);

  // ——— Арена Агранович — по ТЗ: один экран, нижняя треть залита молочной пеной, две полки по бокам ———
  // Прыжок по ТЗ ~40 px (в пене ~29), поэтому всё через 16–32 px, без подпорок:
  //   пол y=208 — в центре пена; у стен тумбы y=192 (на них заходят даже из пены);
  //   над тумбами полки y=160 (с тумбы — 32 px).
  // 4 точки зависания на двух высотах (см. ниже): выше неё всегда есть безопасное место.
  // Коробки на старте — на тумбах и полках; новые падают сверху на полки.
  const row = (localY) => 15 + localY / TILE; // локальная высота арены → строка карты
  m.solid(0, 9, 15, 15); // потолок, справа — проём шахты
  m.solid(0, 0, 15, 29);
  m.solid(1, 14, 28, 29); // пол
  m.decor((p) => A.roaster(p, 6 * TILE + 8, row(208) * TILE), 5 * TILE, 11 * TILE);
  // Пена — тонкий слой у пола в центре (не белый блок на пол-экрана).
  m.paint((p) => A.milkFoam(p, 4 * TILE, AY + 188, 8 * TILE, 20));
  m.zone('foam', 4 * TILE, AY + 188, 8 * TILE, 20);
  m.prop(A.counterBlock(3), 1, row(208)); // тумба слева, колонки 1–3, верх y = 192
  m.prop(A.counterBlock(3), 12, row(208)); // тумба справа, колонки 12–14
  m.prop(A.arenaShelf(4), 1, row(160) + 1); // полка слева, колонки 1–4, y = 160
  m.prop(A.arenaShelf(4), 11, row(160) + 1); // полка справа, колонки 11–14
  // Лесенка полок у стен: 160 → 128 → 96 (по 32 px). Против каждой высоты босса — своя полка:
  // с неё бросок вперёд попадает, а струи не достают (ты чуть выше её центра).
  m.prop(A.arenaShelf(2), 1, row(128) + 1);
  m.prop(A.arenaShelf(2), 13, row(128) + 1);
  m.prop(A.arenaShelf(1), 1, row(96) + 1);
  m.prop(A.arenaShelf(1), 14, row(96) + 1);

  // Ящики не над путём наверх: на тумбах — у стен, на полках — у внутренних краёв.
  box(1, row(192));
  box(14, row(192));
  box(4, row(160));
  box(11, row(160));
  m.pointPx('ammo', 2 * TILE + 8, AY + 32);
  m.pointPx('ammo', 13 * TILE + 8, AY + 32);
  m.decor(
    (p) => {
      for (const cx of [2 * TILE + 8, 13 * TILE + 8]) {
        p.rect(cx - 10, AY + 16, 20, 8, 0x7c7c7c);
        p.hline(cx - 10, AY + 16, 20, 0xbcbcbc);
      }
    },
    0,
    16 * TILE,
  );
  m.point('respawn', 13, row(160));

  // Точки зависания (центр босса) — все низко над пеной, ниже полок: на полках всегда безопасно
  // (струи вверх не летят), бить — с тумб броском вперёд, и успеть вернуться на полку до выстрела.
  // По горизонтали — между тумбами, чтобы не задевать стоящих на них.
  // Три высоты, по две точки — она использует всю арену (по ТЗ точек 4; здесь 6, чтобы подниматься):
  //   низко  — центр y=170: бить с тумб (y=192), безопасно на полках (160);
  //   средне — центр y=132: бить и стоять на полочках (128);
  //   высоко — центр y=100: бить и стоять на верхних полочках (96).
  // По горизонтали — в центре, не задевая полок и тумб у стен.
  for (const y of [170, 132, 100]) {
    m.pointPx('bossPoint', 96, AY + y);
    m.pointPx('bossPoint', 160, AY + y);
  }

  m.segment('down', 0, 0, 16 * TILE, 30 * TILE);
  m.segment('lock', 0, AY, 16 * TILE, 15 * TILE, { boss: 'agranovich' });
  return m;
}
