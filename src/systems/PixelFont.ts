export interface Glyph {
  readonly char: string;
  readonly width: number;
  /** FONT_CELL.height строк одинаковой ширины: строка 0 — надстрочный знак, дальше тело. */
  readonly rows: readonly string[];
}

function parseGlyph(char: string, body: string, mark: string | undefined): Glyph {
  const bodyRows = body.split('|');
  const width = bodyRows[0]?.length ?? 0;
  const top = mark ?? '.'.repeat(width);
  return { char, width, rows: [top, ...bodyRows] };
}

/** Все глифы шрифта (только заглавные; строчные сопоставляются при сборке, см. fontChars). */
export function buildGlyphs(): Glyph[] {
  const out: Glyph[] = [];
  for (const [char, body] of Object.entries(G)) out.push(parseGlyph(char, body, MARKS[char]));
  for (const [char, target] of Object.entries(ALIASES)) {
    if (char === target) continue;
    const body = G[target];
    if (body === undefined) throw new Error(`Font alias ${char} → ${target}: no glyph`);
    out.push(parseGlyph(char, body, MARKS[char]));
  }
  return out;
}

/**
 * Какой глиф рисовать для символа: сам символ, если он есть, иначе его заглавная форма.
 * undefined — символа в шрифте нет.
 */
export function glyphFor(char: string, glyphs: ReadonlyMap<string, Glyph>): Glyph | undefined {
  return glyphs.get(char) ?? glyphs.get(char.toUpperCase());
}

